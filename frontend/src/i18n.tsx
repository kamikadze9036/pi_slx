export function t(en: string, vars?: Record<string, string | number>): string {
  let text = (cs ? dictionary[en] : english[en]) || en;
  if (vars) for (const [key, value] of Object.entries(vars)) text = text.split(`{${key}}`).join(String(value));
  return text;
}

export const formatNumber = (value: number, options?: Intl.NumberFormatOptions) =>
  new Intl.NumberFormat(numberLocale, options).format(value);

function chooseLang(next: Lang) {
  try { window.localStorage.setItem('lang', next); } catch { /* the query parameter below still works */ }
  const url = new URL(window.location.href);
  url.searchParams.set('lang', next);
  window.location.href = url.toString();
}

export function LangSwitch() {
  return <div className="lang-switch" role="group" aria-label={t('Language')}>
    {(['en', 'cs'] as Lang[]).map(value => <button key={value} type="button" className={lang === value ? 'active' : ''}
      aria-pressed={lang === value} onClick={() => lang !== value && chooseLang(value)}>{value === 'cs' ? 'CZ' : 'EN'}</button>)}
  </div>;
}
